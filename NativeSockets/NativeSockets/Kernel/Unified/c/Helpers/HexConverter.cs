        /// <summary>
        ///     Converts a single hexadecimal character to its value.
        /// </summary>
        /// <param name="c">The character code point.</param>
        /// <returns>The numeric value 0-15, or 0xFF if the character is not a hexadecimal digit.</returns>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static int FromChar(int c) => c >= CharToHexLookup.Length ? 0xFF : CharToHexLookup[c];

        /// <summary>
        ///     Returns whether the given character is a hexadecimal digit.
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static bool IsHexChar(int c)
        {
            if (Environment.Is64BitProcess)
            {
                ulong i = (uint)c - '0';
                ulong shift = 18428868213665201664UL << (int)i;
                ulong mask = i - 64;
                return (long)(shift & mask) < 0;
            }

            return FromChar(c) != 0xFF;
        }

        /// <summary>
        ///     Converts a nibble (0-15) to its lowercase hexadecimal character.
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static char ToCharLower(int value)
        {
            value &= 0xF;
            value += '0';
            if (value > '9')
                value += 'a' - ('9' + 1);
            return (char)value;
        }
